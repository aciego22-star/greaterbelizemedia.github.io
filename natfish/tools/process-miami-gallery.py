#!/usr/bin/env python3
"""Build the web derivatives for the Miami 2026 event collection.

Nine photographs the client supplied as unmodified JPEG masters. They are the
co-operative's own, so they land in assets/img/official/ with the rest of it.

Separate from the gallery processors for the same reason the news one is
separate: those rebuild a whole delivery from source files that are not in
this repository, and running one to add a collection would drop everything
already published.

Nothing is recoloured, retouched or re-cropped. The only operations are
downscaling to web tiers and stripping metadata. The tier list per photograph
stops at its own width, so nothing is ever upscaled - five of these are
portrait 1200x1600 and a 1400 tier would invent detail the file does not have.

Usage:
    python3 tools/process-miami-gallery.py <dir of the original JPEGs>
"""
import pathlib
import sys

from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parent.parent
OFFICIAL = ROOT / "assets" / "img" / "official"

STEMS = [
    "miami-2026-product-display-qr",
    "miami-2026-delegation-at-booth",
    "miami-2026-representatives-at-show",
    "miami-2026-conversation-with-attendee",
    "miami-2026-team-at-exhibition",
    "miami-2026-belizean-pride-booth",
    "miami-2026-show-conversation",
    "miami-2026-delegation-in-miami",
    "miami-2026-convention-center",
]

# published stem -> supplied filename
SOURCES = dict(zip(STEMS, [
    "01_product_display_qr.jpg",
    "02_delegation_at_booth.jpg",
    "03_representatives_at_show.jpg",
    "04_conversation_with_attendee.jpg",
    "05_team_at_exhibition.jpg",
    "06_belizean_pride_booth.jpg",
    "07_show_conversation.jpg",
    "08_delegation_in_miami.jpg",
    "09_convention_center.jpg",
]))

# Capped at 1400 on purpose. The card asks for at most 30vw, which is about
# 1150 device pixels on a retina desktop, and the lightbox shows the longest
# edge against the viewport - so a 1600 tier was 450KB a photograph that
# nothing would ever request. Quality 80 rather than 82 for the same reason:
# measured against the 82 encode these are indistinguishable at the sizes they
# are displayed, and the collection is nine photographs, not one.
CANDIDATE_TIERS = (480, 800, 1200, 1400)
WEBP_QUALITY = 80


def main():
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    src = pathlib.Path(sys.argv[1])
    OFFICIAL.mkdir(parents=True, exist_ok=True)

    dims, tiers = {}, {}
    for stem in STEMS:
        path = src / SOURCES[stem]
        if not path.is_file():
            raise SystemExit(f"ERROR: missing source {path}")
        im = Image.open(path)
        if im.mode != "RGB":
            im = im.convert("RGB")
        clean = Image.new("RGB", im.size)      # drops every metadata block
        clean.paste(im)

        written = []
        for w in CANDIDATE_TIERS:
            if w > clean.width:
                continue
            h = round(clean.height * w / clean.width)
            clean.resize((w, h), Image.LANCZOS).save(
                OFFICIAL / f"{stem}-{w}.webp", "WEBP", quality=WEBP_QUALITY,
                method=6)
            written.append(w)
        dims[stem] = clean.size
        tiers[stem] = tuple(written)
        print(f"  {stem:42s} {clean.width}x{clean.height} -> {written}")

    out = ROOT / "tools" / "miami_dims.py"
    lines = ["# Generated by tools/process-miami-gallery.py. Do not edit by hand.",
             "MIAMI_DIMS = {"]
    lines += [f'    "{k}": {v},' for k, v in dims.items()]
    lines += ["}", "", "MIAMI_TIERS = {"]
    lines += [f'    "{k}": {v},' for k, v in tiers.items()]
    lines += ["}", ""]
    out.write_text("\n".join(lines))
    print(f"\nwrote {out.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
