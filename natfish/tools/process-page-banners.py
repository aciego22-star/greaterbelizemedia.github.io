#!/usr/bin/env python3
"""Build the web derivatives for the two page hero banners.

The client supplied these as finished artwork rather than as photographs: a
product collage carrying the "From Our Fishermen to Your Table" slogan for
Seafood & Services, and a single Belizean Pride queen conch carton for What's
New. Each came as a 16:9 desktop composition and a 4:5 phone composition, both
already composed to hold the complete carton, its printed wording and the
slogan inside the frame.

That is why these do not go through the hero or About processors and are not
rendered with `object-fit: cover`. Those crop to the shape of their frame,
which is right for a photograph of a place and wrong for artwork whose whole
point is the printed packaging. Here the frame takes its ratio from the file
instead, so every tier is the complete composition at a smaller size and
nothing is ever cut off.

The supplied 9:16 portrait variants are kept in source-images/ and are not
built. The banner is a block in the page, not a full-screen hero, so a 9:16
frame on a phone would be most of a screen of artwork; the client's note asks
for the tall crop "only if the existing layout is actually tall", and it is
not.

Nothing is recoloured, retouched, re-cropped or sharpened. The only operations
are downscaling to web tiers and stripping metadata.

Usage:
    python3 tools/process-page-banners.py source-images/page-banners-2026
"""
import pathlib
import sys

from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parent.parent
OFFICIAL = ROOT / "assets" / "img" / "official"

# The banner is laid out inside the 1200px container, so about 1152 CSS
# pixels is the widest it is ever painted and a retina desktop asks for 2300.
# The supplied file is 1920, so that is the ceiling and no tier above it is
# invented.
#
# There is no 1600 and no 720, and that is measured rather than arbitrary. A
# srcset picks the narrowest tier that covers width x DPR, so with 800, 1200
# and 1920 present the only requests 1600 could ever answer are the ones
# between 1200 and 1600 - roughly DPR 1.05 to 1.39, which is Windows at 125%
# scaling. Those requests are answered by 1920 instead, so nobody is served a
# smaller file for the want of 1600; the tier only ever saved bandwidth, and
# at a third of a megabyte across the two banners it was the most expensive
# way left to save any. 720 on the phone crop is the same case between 540
# and 720. Both were dropped when the package reached the 30 MiB ceiling, in
# preference to re-encoding the artwork at a lower quality: printed carton
# wording is the whole subject here, and softening it to save bytes would have
# defeated the point of shipping it.
DESKTOP_TIERS = (800, 1200, 1920)
MOBILE_TIERS = (360, 540, 1080)

# 80 rather than 82. These are flat artwork with large areas of even colour
# and a lot of small printed type; compared against an 82 encode at 1200px the
# printed lines on the cartons are indistinguishable, and the collage is a
# third of a megabyte either way.
WEBP_QUALITY = 80

# published stem -> supplied filename
BANNERS = {
    "banner-seafood-services-desktop": "seafood-services-desktop-1920x1080.webp",
    "banner-seafood-services-mobile": "seafood-services-mobile-1080x1350.webp",
    "banner-whats-new-conch-desktop": "whats-new-conch-desktop-1920x1080.webp",
    "banner-whats-new-conch-mobile": "whats-new-conch-mobile-1080x1350.webp",
}

TIERS_FOR = {
    "desktop": DESKTOP_TIERS,
    "mobile": MOBILE_TIERS,
}


def main():
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    src = pathlib.Path(sys.argv[1])
    OFFICIAL.mkdir(parents=True, exist_ok=True)

    dims, tiers = {}, {}
    for stem, name in BANNERS.items():
        path = src / name
        if not path.is_file():
            raise SystemExit(f"ERROR: missing source {path}")
        im = Image.open(path)
        if im.mode != "RGB":
            im = im.convert("RGB")
        clean = Image.new("RGB", im.size)      # drops every metadata block
        clean.paste(im)

        candidates = TIERS_FOR[stem.rsplit("-", 1)[1]]
        written = []
        for w in candidates:
            if w > clean.width:
                continue
            h = round(clean.height * w / clean.width)
            resized = clean if w == clean.width else clean.resize(
                (w, h), Image.LANCZOS)
            resized.save(OFFICIAL / f"{stem}-{w}.webp", "WEBP",
                         quality=WEBP_QUALITY, method=6)
            written.append(w)
        dims[stem] = clean.size
        tiers[stem] = tuple(written)
        print(f"  {stem:36s} {clean.width}x{clean.height} -> {written}")

    out = ROOT / "tools" / "banner_dims.py"
    lines = ["# Generated by tools/process-page-banners.py. Do not edit by hand.",
             "BANNER_DIMS = {"]
    lines += [f'    "{k}": {v},' for k, v in dims.items()]
    lines += ["}", "", "BANNER_TIERS = {"]
    lines += [f'    "{k}": {v},' for k, v in tiers.items()]
    lines += ["}", ""]
    out.write_text("\n".join(lines))
    print(f"\nwrote {out.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
